def quicksort(arr: list[int]) -> list[int]:
    """
    Функция принимает массив целых чисел
    и возвращает отсоритрованный массив целых чисел.
    Используется метод сортировки quicksort.

    Докажем корректность данной функции.
    {True} 
    quicksort(arr) 
    {arr для arr.length < 2; arr[0] <= ... <= arr[n] <= ... <=arr[arr.length-1] для arr.length >= 2}
    
    Рассмотрим строки:
    if len(arr) < 2:
        return arr[:]

    Докажем для arr.length < 2.
    Так как предусловие True, то первая ветка условия выполнится при arr.length < 2
    и будет возвращен сам массив. Этим доказали часть постусловия "arr для arr.length < 2".

    Так как предусловие True, то ветвь "else" получит условие arr.length >= 2. То есть нужно
    доказать, что остальная часть программы вернёт постусловие 
    "arr[0] <= ... <= arr[n] <= ... <=arr[arr.length-1]".

    pivot:int = arr[-1]
    Эта строка выполняется при предусловии arr.length >= 2, то есть в массиве минимум 2 элемента,
    поэтому переменной pivot всегда будет присвоен последний элемент массива.

    less_pivot: list[int] = []
    greater_or_equal_pivot: list[int] = []
    Это просто присвоение переменным пустого массива - оно всегда сработает.

    for i in range(len(arr) - 1):
    Эта строка выполняется при предусловии arr.length >= 2, то есть в массиве минимум 2 элемента,
    поэтому цикл выполнится хотя бы один раз. При этом так как количество выполнений цикла 
    "len(arr) - 1", переполнения не возникнет. Так как переменная цикла возрастает монотонно на 1,
    цикл точно завершится. Цикл затронет все элементы массива кроме последнего.
    Примем инвариант цикла: 
    {0 <= i <= length.arr - 1, 
     less_pivot пуст или содержит все элементы arr меньше pivot,
     greater_or_equal_pivot пуст или содержит все элементы arr больше или равные pivot
    }
    
        if arr[i] < pivot:
            less_pivot.append(arr[i])
            continue
    Часть инварианта "0 <= i <= length.arr - 1" выполняется исходя из опредедления цикла.
    В цикле нужно рассмотреть обе ветви. 
    1-я выполняется при предусловии arr.length >= 2 и arr[i] < pivot, при этом цикл выполнится
    над всеми элементами кроме последнего. Таким образом в массиве less_pivot будут собраны все элементы
    массива меньше pivot (либо он будет пуст). Таким образом выполняется 2-я часть инварианта.

        greater_or_equal_pivot.append(arr[i])
    2-я выполняется при предусловии arr.length >= 2 и arr[i] >= pivot, при этом цикл выполнится
    над всеми элементами кроме последнего. Таким образом в массиве greater_or_equal_pivot будут 
    собраны все элементы массива большие или равные pivot (либо он будет пуст). Таким образом 
    выполняется 3-я часть инварианта.

    result: list[int] = []
    Это просто присвоение переменной пустого массива - оно всегда сработает.

    result.extend(quicksort(less_pivot))
    Рекурсивный вызов функции quicksort. Производится только над исходным массивом, содержащим
    не менее 2-х элементов. Функции передаётся пустой массив, либо значения исходного массива
    меньшие, чем pivot. Рекурсивные вызовы "сойдутся" (не будет бесконечной рекурсии), так как
    на каждом шаге максимально будет передан массив без последнего элемента. Длина массива конечна,
    для пустого массива или массива из одного элемента дальнейшей рекурсии не будет, поэтому глубина 
    рекурсии будет конечна. На каждом шаге рекурсии элементы в less_pivot будут меньше, чем pivot (
    это было рассмотрено в цикле выше). На финальном шаге рекурсии массив less_pivot будет пуст (если pivot
    самый меньший элемент списка) или состоять из одного элемента (тогда список из одного элемента
    меньше pivot и доказано, что первый элемент отсортированного списка будет меньше второго). При возврате с  
    рекурсии все элементы списка будут меньше текущего pivot. Так на каждом шаге элементы меньше pivot
    будут отсортированы по возрастанию.

    result.append(pivot)

    result.extend(quicksort(greater_or_equal_pivot))
    Рекурсивный вызов функции quicksort. Производится только над исходным массивом, содержащим
    не менее 2-х элементов. Функции передаётся пустой массив, либо значения исходного массива
    большие или равные pivot. Рекурсивные вызовы "сойдутся" (не будет бесконечной рекурсии), так как
    на каждом шаге максимально будет передан массив без последнего элемента. Длина массива конечна,
    для пустого массива или массива из одного элемента дальнейшей рекурсии не будет, поэтому глубина 
    рекурсии будет конечна. На каждом шаге рекурсии элементы в greater_or_equal_pivot будут больше или 
    равны pivot (это было рассмотрено в цикле выше). На финальном шаге рекурсии массив greater_or_equal_pivot
    будет пуст (если pivot самый больший элемент списка) или состоять из одного элемента (тогда список
    из одного элемента больше или равен pivot и доказано, что последний элемент отсортированного списка
    будет больше или равен предпоследнего). При возврате с рекурсии все элементы списка будут больше или 
    равны текущему pivot. Так на каждом шаге элементы больше или равные pivot будут отсортированы
    по возрастанию.

    Итого весь список будет отсортирован по возрастанию. Корректность работы функции доказана.

    """
    # Для пустого массива и массива из одного элемента возвращаем их же.
    if len(arr) < 2:
        return arr[:] # Используем срез [:] чтобы вернуть копию массива.

    # В качестве опорного элемента (pivot) использую последний элемент массива.
    pivot:int = arr[-1]

    # Объявляю два списка:
    # 1-й список с элементами, меньшими, чем pivot.
    less_pivot: list[int] = []
    # 2-й список с элементами, большими или равными pivot.
    greater_or_equal_pivot: list[int] = []

    # В цикле по исходному списку (без последнего элемента) 
    # заполняю оба объявленных списка.
    for i in range(len(arr) - 1):
        if arr[i] < pivot:
            less_pivot.append(arr[i])
            continue
        greater_or_equal_pivot.append(arr[i])

    # Объявляю список - результат.
    result: list[int] = []

    # Добавляю в результат отсортированный список из чисел, меньших, чем pivot.
    result.extend(quicksort(less_pivot))

    # Добавляю в результат pivot.
    result.append(pivot)

    # Добавляю в результат отсортированный список из чисел, больших или равных pivot.
    result.extend(quicksort(greater_or_equal_pivot))

    # Возвращаю результат.
    return result


def main() -> None:
    test_list: list[int] = [7, 3, 10, 6, 4]
    print(f"Исходный список: {test_list}. Отсортированный список: {quicksort(test_list)}.")


if __name__ == "__main__":
    main()
