def find_max(arr: list[int]) -> int:
    """
    Функция find_max ищет максимальное значение в массиве целых чисел.
    В массиве должен быть один или более элемент.
    Докажем корректность данной функции.
    {arr.length > 0} find_max(arr) {result = max(arr)}
    
    Строчка max_value: int = arr[0]
    В max_value будет первый элемент массива.
    Выхода за индекс не будет, так как, исходя из предусловия, один элемент в массиве есть.

    Если массив из одного элемента, то цикл не выполняется совсем, переменная цикла не инициализируется
    и функция возвращает значение первого элемента, что является правильным значением максимума
    для массива из одного элемента.

    Докажем теперь для массива из 2 и более элементов.

    Рассмотрим массив из 2 элементов. Цикл выполнится один раз, arr[i] будет содержать
    один элемент. Доказательство аналогично доказательству корректности функции max.
    После цикла переменная max_value будет содержать максимальное значение для первых двух элементов,
    счётчик цикла i будет равен 1 (длина массива минус 1). Для 2 элементов доказали.

    Докажем теперь для n > 2 элементов массива.

    Примем инвариант max_value - это максимум для i + 1 первых элементов массива, i < arr.length.

    Для массива из 2-х элементов инвариант соблюдается.
    На следующем шаге max_value будет сравнено с i-м следующим элементом массива.
    Если этот i-й элемент будет больше max_value, то его значение будет сохранено
    в max_value, если меньше, то max_value не изменится. i не превысит arr.length, так как
    перебор в цикле идёт до arr.length - 1 и на последней итерации max_value будет сравнено
    с последним элементом массива.

    Переменная массива нарастает монотонно и иметт ограничение, поэтому цикл всегда исполнится.

    Тем самым доказана полная корректность данной функции.
    """

    assert len(arr) > 0 # Проверка предусловия
    max_value: int = arr[0]
    for i in range(len(arr) - 1):
        if arr[i] > max_value:
            max_value = arr[i]
    return max_value


def main() -> None:
    test_arr:list[int] = [6, 9, 3, 56, 11]
    print(f"Максимальное значение в массиве {test_arr} равно {find_max(test_arr)}")


if __name__ == "__main__":
    main()
